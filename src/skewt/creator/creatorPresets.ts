export function weismanKlemp(): CreatorLevel[] {
  const o: CreatorLevel[] = [];
  let pi = 1;
  let thp = 300;
  for (let z = 0; z <= 17e3; z += 500) {
    const q = z / 12e3;
    const th =
      z <= 12e3
        ? 300 + 43 * Math.pow(q, 1.25)
        : 343 * Math.exp((g / (cp * 213)) * (z - 12e3));
    if (z > 0) pi -= ((g / cp) * 500 * (1 / thp + 1 / th)) / 2;
    thp = th;
    const p = 1e3 * Math.pow(pi, 1 / kap);
    const T = th * pi - K;
    const rh = z <= 12e3 ? 1 - 0.75 * Math.pow(q, 1.25) : 0.25;
    const w = Math.min(14, Math.max(0.01, rh * wm(p, T)));
    const ph = Math.min(1, z / 6e3) * (Math.PI / 2);
    const u = (20 * (1 - Math.cos(ph))) / KT;
    const v = (20 * Math.sin(ph)) / KT;
    o.push({
      p,
      T,
      Td: Math.min(Tdw(p, w), T),
      d: dirOf(u, v),
      s: Math.hypot(u, v),
    });
  }
  return o;
}


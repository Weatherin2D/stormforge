export function flipHemisphere(levels: CreatorLevel[]): void {
  levels.forEach((l) => {
    l.d = (540 - l.d) % 360;
  });
}

export function loadPreset(id: string, hemi: Hemisphere): CreatorLevel[] {
  const levels =
    id === "0"
      ? weismanKlemp()
      : (PRESETS[id] ?? SUP).map((o) => ({ ...o }));
  const native = NAT_HEMI[id] ?? "N";
  if (hemi !== native) flipHemisphere(levels);
  return levels;
}
